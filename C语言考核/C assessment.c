//6.#define和const常量的区别
//(1)处理阶段不同
//   #define：预处理阶段直接文本替换，无类型检查
//   const：编译阶段处理，是带数据类型的变量
//(2)数据类型
//   #define：无类型，纯文本替换，容易出错
//   const：有明确类型，运算遵循语法规则
//(3)内存占用
//   #define：不分配内存，仅替换文本
//   const：占用内存，存放在只读数据区
//(4)作用域
//   #define：默认全局有效，#undef才能取消
//   const：遵循变量作用域（局部/全局）
//(5)调式优势
//   #define：调试器看不到宏名称，只有替换后文本
//   const：调试可直接看到常量名，方便排错
//(6)指针、函数参数
//   const可修饰指针、函数形参；#define做不到类型限定
// 
