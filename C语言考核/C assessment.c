#include<stdio.h>
void sort(int arr[], int n)
{
	int i, j, temp;
	for (i = 0;i < n - 1;i++)
	{
		for (j = 0;j < n - 1 - i;j++)
		{
			if (arr[j] > arr[j + 1])
			{
				temp = arr[j];
				arr[j] = arr[j + 1];
				arr[j + 1] = temp;
			}
		}
	}
}
int main()
{
	int i = 0;
	int a[] = { 5,2,4,1,3 };
	int len = sizeof(a) / sizeof(a[0]);
	sort(a, len);
	for (i = 0;i < len;i++)
		printf("%d", a[i]);
	return 0;
}
